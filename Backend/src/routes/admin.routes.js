const express = require("express");
const authMiddleware = require("../middleware/authMiddleware");
const { getOverview } = require("../controllers/admin.controller");
const { getAnalytics } = require("../microservices/analytics/analytics.controller");
const { listUsers, listArchivedUsers, getUserDetails } = require("../controllers/adminUsers.controller");
const { moderateAccount } = require("../controllers/accountModeration.controller");
const { archiveAccount } = require("../controllers/accountArchive.controller");
const { manageModerator } = require("../controllers/staff.controller");
const { adminOnly, requirePermission, requireModerationPermission } = require("../middleware/staffPermission");
const reports = require("../controllers/reports.controller");
const verification = require("../controllers/profileVerification.controller");
const content = require("../controllers/contentModeration.controller");
const oversight = require("../controllers/oversight.controller");
const support = require("../controllers/support.controller");
const announcements = require("../controllers/announcements.controller");
const audit = require("../controllers/staffAudit.controller");
const platform = require("../controllers/platform.controller");
const adverts = require("../controllers/adverts.controller");
const audited = require("../middleware/staffAudit");
const record = (category, targetKind, targetParam, route, action) => audited({ category, targetKind, targetParam, route, action });

const router = express.Router();
router.use(authMiddleware(["admin", "moderator"]));
router.get("/overview", adminOnly, getOverview);
router.get("/adverts", adminOnly, adverts.noStore, adverts.listStaff);
router.post("/adverts", record("adverts", "advert", null, "/adverts", "create"), adminOnly, adverts.noStore, adverts.create);
router.get("/adverts/:advertId", adminOnly, adverts.noStore, adverts.get);
router.patch("/adverts/:advertId", record("adverts", "advert", "advertId", "/adverts/:advertId", "update"), adminOnly, adverts.noStore, adverts.update);
router.post("/adverts/:advertId/actions", record("adverts", "advert", "advertId", "/adverts/:advertId/actions"), adminOnly, adverts.noStore, adverts.act);
router.get("/platform/health", adminOnly, platform.noStore, platform.getHealth);
router.get("/platform/settings", adminOnly, platform.noStore, platform.getSettings);
router.patch("/platform/settings", record("settings", "platform", null, "/platform/settings", "update"), adminOnly, platform.noStore, platform.updateSettings);
router.get("/audit", adminOnly, audit.noStore, audit.list);
router.get("/audit/:auditId", adminOnly, audit.noStore, audit.get);
router.get("/announcements", adminOnly, announcements.noStore, announcements.listStaff);
router.post("/announcements", record("announcements", "announcement", null, "/announcements", "create"), adminOnly, announcements.noStore, announcements.create);
router.get("/announcements/:announcementId", adminOnly, announcements.noStore, announcements.get);
router.patch("/announcements/:announcementId", record("announcements", "announcement", "announcementId", "/announcements/:announcementId", "update"), adminOnly, announcements.noStore, announcements.update);
router.post("/announcements/:announcementId/actions", record("announcements", "announcement", "announcementId", "/announcements/:announcementId/actions"), adminOnly, announcements.noStore, announcements.act);
router.get("/support", adminOnly, support.noStore, support.listStaff);
router.get("/support/:ticketId", adminOnly, support.noStore, support.getStaff);
router.post("/support/:ticketId", record("support", "support", "ticketId", "/support/:ticketId"), adminOnly, support.noStore, support.act);
router.get("/operations", adminOnly, oversight.noStore, oversight.list);
router.get("/operations/:type/:recordId", adminOnly, oversight.noStore, oversight.get);
router.post("/operations/:type/:recordId", record("operations", (p) => p.type, "recordId", "/operations/:type/:recordId"), adminOnly, oversight.noStore, oversight.act);
router.get("/content", requirePermission("content.read"), content.noStore, content.listProfiles);
router.get("/content/:type/:profileId", requirePermission("content.read"), content.noStore, content.getProfile);
router.post("/content/:type/:profileId", record("content", (p) => p.type, "profileId", "/content/:type/:profileId"), requirePermission("content.read"), requirePermission("content.manage"), content.noStore, content.moderate);
router.get("/verification", adminOnly, verification.noStore, verification.listProfiles);
router.get("/verification/:type/:profileId", adminOnly, verification.noStore, verification.getProfile);
router.post("/verification/:type/:profileId", record("verification", (p) => p.type, "profileId", "/verification/:type/:profileId"), adminOnly, verification.noStore, verification.verifyProfile);
router.get("/analytics", requirePermission("analytics.read"), getAnalytics);
router.get("/users", requirePermission("users.read"), listUsers);
router.get("/archive", adminOnly, listArchivedUsers);
router.get("/users/:userId", requirePermission("users.read"), getUserDetails);
router.post("/users/:userId/moderation", record("moderation", "account", "userId", "/users/:userId/moderation"), requireModerationPermission, moderateAccount);
router.post("/users/:userId/archive", record("archive", "account", "userId", "/users/:userId/archive"), adminOnly, archiveAccount);
router.post("/users/:userId/staff", record("staff", "account", "userId", "/users/:userId/staff"), adminOnly, manageModerator);
router.get("/reports", requirePermission("reports.read"), reports.noStore, reports.listStaff);
router.get("/reports/reviewers", adminOnly, reports.noStore, reports.reviewers);
router.get("/reports/:reportId", requirePermission("reports.read"), reports.noStore, reports.getStaff);
router.post("/reports/:reportId/actions", record("reports", "report", "reportId", "/reports/:reportId/actions"), requirePermission("reports.read"), requirePermission("reports.manage"), reports.noStore, reports.updateReport);

module.exports = router;
